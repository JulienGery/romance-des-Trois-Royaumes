#!/usr/bin/env python3
"""Bake a Level5FontAtlas output (atlas.png + atlas.json) into a fixed-cell A4 page.

Each glyph is copied into a CELLxCELL cell at its own (offsetX, offsetY) so that the
engine only needs: cell index -> UV, plus a per-glyph advance table (proportional).
Outputs (in --out): page_<name>.alpha (w*h bytes), glyphs_<name>.json, font_<name>.h, preview PNG.
"""
import argparse, json, os, struct, sys, zlib


def read_png_alpha(path):
    d = open(path, 'rb').read(); i = 8; idat = b''
    while i < len(d):
        l, = struct.unpack('>I', d[i:i + 4]); t = d[i + 4:i + 8]
        if t == b'IHDR': w, h, bd, ct = struct.unpack('>IIBB', d[i + 8:i + 18])
        if t == b'IDAT': idat += d[i + 8:i + 8 + l]
        i += 12 + l
    assert bd == 8 and ct == 6, 'expects RGBA8'
    raw = zlib.decompress(idat); bpp = 4; stride = w * bpp; out = bytearray(); prev = bytearray(stride); p = 0
    for _ in range(h):
        f = raw[p]; line = bytearray(raw[p + 1:p + 1 + stride]); p += 1 + stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0; b = prev[x]; c = prev[x - bpp] if x >= bpp else 0
            if f == 1: line[x] = (line[x] + a) & 255
            elif f == 2: line[x] = (line[x] + b) & 255
            elif f == 3: line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                pr = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                line[x] = (line[x] + pr) & 255
        out += line; prev = line
    return w, h, bytes(out[3::4])


def write_gray_png(path, w, h, g):
    raw = b''.join(b'\0' + g[y * w:(y + 1) * w] for y in range(h))
    def ch(t, b): return struct.pack('>I', len(b)) + t + b + struct.pack('>I', zlib.crc32(t + b) & 0xffffffff)
    open(path, 'wb').write(b'\x89PNG\r\n\x1a\n' + ch(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 0, 0, 0, 0)) + ch(b'IDAT', zlib.compress(raw, 9)) + ch(b'IEND', b''))


def packed_utf8(cp):
    b = chr(cp).encode('utf8'); return int.from_bytes(b, 'big')   # same packing as UTF8_iter (0x0052D79C)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('atlas_dir'); ap.add_argument('--name', required=True)
    ap.add_argument('--out', default='build'); ap.add_argument('--cell', type=int, default=16); ap.add_argument('--cellh', type=int, default=0)
    ap.add_argument('--page', type=int, default=256); a = ap.parse_args()
    meta = json.load(open(os.path.join(a.atlas_dir, 'atlas.json')))
    aw, ah, src = read_png_alpha(os.path.join(a.atlas_dir, 'atlas.png'))
    C, P = a.cell, a.page; CH = a.cellh or C; cols = P // C; rows = P // CH
    glyphs = sorted((g for g in meta['glyphs'] if g['codePoint'] != 0xA0 and g['codePoint'] != 0x202F and g['codePoint'] != 0x3000), key=lambda g: packed_utf8(g['codePoint']))
    assert len(glyphs) <= cols * rows, 'too many glyphs for page'
    page = bytearray(P * P); warn = []
    table = []
    for idx, g in enumerate(glyphs):
        cx, cy = (idx % cols) * C, (idx // cols) * CH
        ox, oy, w, h = g['offsetX'], g['offsetY'], g['width'], g['height']
        bx = min(0, ox)                      # negative left bearing: shift ink right inside the cell, renderer draws the cell at pen+bx
        if w and h:
            if ox - bx + w > C or oy < 0 or oy + h > CH: warn.append((g['character'], ox, oy, w, h))
            for y in range(h):
                for x in range(w):
                    if 0 <= ox - bx + x < C and 0 <= oy + y < CH:
                        page[(cy + oy + y) * P + cx + ox - bx + x] = src[(g['y'] + y) * aw + g['x'] + x]
        table.append({'cp': g['codePoint'], 'ch': g['character'], 'packed': packed_utf8(g['codePoint']), 'index': idx, 'advance': g['advance'], 'bearing_x': bx, 'ink_w': w, 'ink_h': h, 'ox': ox, 'oy': oy})
    os.makedirs(a.out, exist_ok=True)
    open(os.path.join(a.out, f'page_{a.name}.alpha'), 'wb').write(bytes(page))
    write_gray_png(os.path.join(a.out, f'page_{a.name}.png'), P, P, bytes(page))
    json.dump({'name': a.name, 'cell_w': C, 'cell_h': CH, 'page': P, 'cols': cols, 'rows': rows, 'lineHeight': meta['lineHeight'], 'fallbackCodePoint': meta['fallbackCodePoint'], 'glyphs': table}, open(os.path.join(a.out, f'glyphs_{a.name}.json'), 'w'), ensure_ascii=False, indent=1)
    fb = next((t['index'] for t in table if t['cp'] == meta['fallbackCodePoint']), 0)
    with open(os.path.join(a.out, f'font_{a.name}.h'), 'w') as f:
        f.write(f'/* generated by bake_french_atlas.py ({a.name}) - codes are UTF8_iter-packed, sorted ascending */\n#ifndef FONT_{a.name.upper()}_H\n#define FONT_{a.name.upper()}_H\n#include <stdint.h>\n')
        f.write(f'#define FR_{a.name.upper()}_COUNT {len(table)}\n#define FR_{a.name.upper()}_CELL_W {C}\n#define FR_{a.name.upper()}_CELL_H {CH}\n#define FR_{a.name.upper()}_COLS {cols}\n#define FR_{a.name.upper()}_LINE {meta["lineHeight"]}\n#define FR_{a.name.upper()}_FALLBACK_INDEX {fb}\n')
        f.write(f'static const uint32_t fr_{a.name}_codes[{len(table)}] = {{' + ','.join('0x%X' % t['packed'] for t in table) + '};\n')
        f.write(f'static const uint8_t fr_{a.name}_adv[{len(table)}] = {{' + ','.join(str(t['advance']) for t in table) + '};\n')
        f.write(f'static const int8_t fr_{a.name}_bearing[{len(table)}] = {{' + ','.join(str(t['bearing_x']) for t in table) + '};\n')
        f.write(f'static const uint8_t fr_{a.name}_inkw[{len(table)}] = {{' + ','.join(str(t['ink_w']) for t in table) + '};\n#endif\n')
    print(f'{a.name}: {len(table)} glyphs, cell {C}x{CH}, page {P}x{P}, fallback idx {fb}, warnings: {len(warn)}')
    for w in warn[:20]: print('  warn', w)


if __name__ == '__main__': main()
