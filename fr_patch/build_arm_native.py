#!/usr/bin/env python3
"""Build the ARM-patched ExeFS code (no recompiled library needed): compiles overrides/fr_text.c for the console CPU with
arm-none-eabi-gcc (fr_arm/overrides.h = native runtime), spreads the code over dead-code cavities of .text (build/cavities.json, found by
cavity_search.py), hooks the game functions with `b stub` at their entry, adds trampolines for the displaced first instruction(s), and
raises the exheader .bss size (state + private C stacks live in the extension).
Usage: build_arm_native.py <code.bin in> <code.bin out> <exheader in> <exheader out>"""
import json, os, re, struct, subprocess, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
BASE = 0x100000
BSS_ORG, BSS_LEN = 0x81F000, 0x40000           # extension of .bss (page after the old end 0x81E978)
PASS = {0x2373E0, 0x2372A4, 0x541794, 0x2DE710, 0x236170, 0x237858, 0x542430, 0x541710, 0x21B87C, 0x52D44C, 0x52CAF8, 0x120E0C, 0x2DEA30, 0x2DFAD8}
SRC = os.path.join(ROOT, 'overrides', 'fr_text.c'); FRARM = os.path.join(ROOT, 'fr_arm')
ARCH = ['-mcpu=arm1176jzf-s', '-mfpu=vfp', '-mfloat-abi=softfp']
CFLAGS = [os.environ.get('FR_ARM_OPT', '-Os'), '-mthumb', '-mcpu=arm1176jzf-s', '-mfpu=vfp', '-mfloat-abi=softfp', '-fno-jump-tables'] + ['-ffreestanding', '-fno-pic', '-fno-exceptions', '-fno-inline-functions-called-once', '-ffunction-sections', '-fdata-sections', '-w', '-DFR_NATIVE',
          '-I', FRARM, '-I', os.path.join(ROOT, 'overrides')]
GCC = 'arm-none-eabi-gcc'

def run(cmd, **k): return subprocess.run(cmd, check=True, **k)
def out(cmd): return subprocess.check_output(cmd).decode()

def main(cin, cout, xin, xout):
    code = bytearray(open(cin, 'rb').read())
    def rd(va): return struct.unpack_from('<I', code, va - BASE)[0]
    text = open(SRC).read()
    only = os.environ.get('FR_ARM_HOOKS')
    ovr = [int(m, 16) for m in re.findall(r'RECOMP_OVERRIDE\((0x[0-9A-Fa-f]+)\)', text)]
    spell = {}
    for m in set(re.findall(r'RECOMP_(?:OVERRIDE|ORIGINAL)\((0x[0-9A-Fa-f]+)\)', text)): spell[int(m, 16)] = m
    hooked = [a for a in dict.fromkeys(ovr) if a not in PASS]
    # ---- trampolines (assembly): displaced instruction(s) + branch back
    tr = ['@ generated', '        .arm', '        .syntax unified']
    for a in hooked:
        i0, i1 = rd(a), rd(a + 4)
        tr.append(f'        .section .text.fr_tramp_{a:08X},"ax"\n        .global fr_tramp_{a:08X}\nfr_tramp_{a:08X}:')
        if (i0 & 0x0F7F0000) == 0x051F0000:                       # ldr rN,[pc,#imm]: copy the literal next to the trampoline
            assert (i1 & 0xFFFF0000) == 0xE92D0000, hex(i1)
            lit = rd(a + 8 + (i0 & 0xFFF))
            tr += [f'        .word {(i0 & 0xFFFFF000) | 4:#x}', f'        .word {i1:#x}', f'        b {a + 8:#x}', f'        .word {lit:#x}']
        else:
            assert (i0 & 0xFFFF0000) in (0xE92D0000, 0xE52D0000), f'{a:#x}: first insn {i0:#010x} is not a push'
            tr += [f'        .word {i0:#x}', f'        b {a + 4:#x}']
    with tempfile.TemporaryDirectory() as td:
        h = ['/* generated by build_arm_native.py */']
        for a in hooked: h.append(f'extern const uint32_t fr_tramp_{a:08X}[];')
        for a in dict.fromkeys(ovr + [int(m, 16) for m in re.findall(r'RECOMP_ORIGINAL\((0x[0-9A-Fa-f]+)\)', text)]):
            tgt = f'(uint32_t)fr_tramp_{a:08X}' if a in hooked else f'{a:#x}u'
            h.append(f'static inline void fr_orig_{spell[a]}(Context *c) {{ fr_call_guest(c, {tgt}); }}')
        for m in sorted(set(re.findall(r'\bf_([0-9A-F]{8})\b', text + open(os.path.join(ROOT, 'overrides', 'frfont.h')).read()))):
            a = int(m, 16); tgt = f'(uint32_t)fr_tramp_{a:08X}' if a in hooked else f'{a:#x}u'
            h.append(f'#define f_{m}(c) fr_call_guest((c), {tgt})')
        open(os.path.join(FRARM, 'hooks.h'), 'w').write('\n'.join(h) + '\n')
        stubs = ['@ generated']
        for a in hooked:
            stubs.append(f'        .global stub_{a:08X}\nstub_{a:08X}:\n        ldr     r12, =override_{spell[a]}\n        b       fr_enter')
        open(os.path.join(FRARM, 'stubs.S'), 'w').write('\n'.join(stubs) + '\n')
        open(os.path.join(td, 'tramps.S'), 'w').write('\n'.join(tr) + '\n')
        objs = []
        for src, extra in (('fr_text.c', []), ('rt.c', ['-marm']), ('rt.S', ['-x', 'assembler-with-cpp']), ('tramps.S', ['-x', 'assembler-with-cpp'])):
            f = SRC if src == 'fr_text.c' else (os.path.join(td, src) if src == 'tramps.S' else os.path.join(FRARM, src))
            o = os.path.join(td, src + '.o'); run([GCC] + CFLAGS + extra + ['-c', f, '-o', o, '-I', FRARM]); objs.append(o)
        # ---- pack input sections into the cavities (first fit decreasing)
        secs = []
        for o in objs:
            for line in out(['arm-none-eabi-objdump', '-h', o]).split('\n'):
                p = line.split()
                if len(p) >= 7 and re.match(r'\d+$', p[0]) and (p[1].startswith('.text') or p[1].startswith('.rodata')):
                    size = int(p[2], 16); al = 1 << int(p[-1].split('**')[1]) if '**' in p[-1] else 4
                    if size: secs.append((p[1], os.path.basename(o), size, max(al, 4)))
        cav = json.load(open(os.path.join(HERE, 'cavities.json')))
        # the original measure FUN_0052CEA4 is fully replaced by the port (never called, its entry is hooked): the rest of its body is free
        cav.append([0x52CEA8, 0x52D340])
        # Thumb `bl` reaches +-4 MiB: keep every fragment within one 4 MiB window so no long-branch stubs are needed
        cav = [c for c in cav if c[0] >= 0x180000 and c[1] <= 0x57F000]
        frags = sorted(([a, b - a, a] for a, b in cav if b - a >= 128), key=lambda r: -r[1])   # [org, free, cursor]
        place = {}
        for name, o, size, al in sorted(secs, key=lambda s: -s[2]):
            for fi, fr in enumerate(frags):
                cur = (fr[2] + al - 1) & ~(al - 1)
                if cur + size <= fr[0] + fr[1]:
                    place.setdefault(fi, []).append((name, o)); fr[2] = cur + size; break
            else: raise SystemExit(f'no cavity left for section {name} ({size} bytes)')
        used = sum(f[2] - f[0] for f in frags)
        ld = ['MEMORY {']
        for fi in place: ld.append(f'    F{fi} (rx) : ORIGIN = {frags[fi][0]:#x}, LENGTH = {frags[fi][1]:#x}')
        ld += [f'    BSS (rw) : ORIGIN = {BSS_ORG:#x}, LENGTH = {BSS_LEN:#x}', '}', 'SECTIONS {']
        for fi, items in place.items():
            ld.append(f'    .f{fi} : {{')
            for name, o in items: ld.append(f'        *{o}({name})')
            ld.append(f'        . = ALIGN(4);\n    }} > F{fi}')
        ld += ['    .bss (NOLOAD) : { *(.bss*) *(COMMON) . = ALIGN(8); } > BSS',
               '    /DISCARD/ : { *(.ARM.exidx*) *(.ARM.extab*) *(.comment) *(.note*) *(.data*) *(.eh_frame*) *(.text*) *(.rodata*) }', '}']
        open(os.path.join(td, 'link.ld'), 'w').write('\n'.join(ld) + '\n')
        elf = os.path.join(td, 'fr.elf')
        run([GCC, '-nostdlib', '-nostartfiles'] + ARCH + ['-Wl,-T,' + os.path.join(td, 'link.ld'), '-Wl,--gc-sections', '-Wl,--use-blx', '-Wl,-e,fr_enter', '-Wl,-Map,' + os.path.join(td, 'map.txt'), '-o', elf] + objs)
        os.makedirs(os.path.join(HERE, 'build'), exist_ok=True); run(['cp', elf, os.path.join(HERE, 'build', 'fr_native.elf')])
        syms = {}
        for line in out(['arm-none-eabi-nm', elf]).split('\n'):
            p = line.split()
            if len(p) == 3: syms[p[2]] = int(p[0], 16)
        parts = {}
        for fi in place:
            raw = os.path.join(td, f'f{fi}.bin'); run(['arm-none-eabi-objcopy', '-O', 'binary', '-j', f'.f{fi}', elf, raw]); parts[fi] = open(raw, 'rb').read()
        sz = out(['arm-none-eabi-size', elf]).split('\n')[1].split()
    print(f'native code {sum(len(p) for p in parts.values())} bytes in {len(parts)} cavities, bss used {sz[2]} bytes')
    for fi, blob in parts.items():
        assert len(blob) <= frags[fi][1]
        code[frags[fi][0] - BASE:frags[fi][0] - BASE + len(blob)] = blob
    for a in hooked:
        if only is not None and f'{a:x}' not in only.lower().split(','): continue
        struct.pack_into('<I', code, a - BASE, 0xEA000000 | (((syms[f'stub_{a:08X}'] - (a + 8)) >> 2) & 0xFFFFFF))
        print(f'hook {a:#08x} -> stub {syms[f"stub_{a:08X}"]:#x}, original via {syms.get(f"fr_tramp_{a:08X}", 0):#x}')
    open(cout, 'wb').write(code)
    x = bytearray(open(xin, 'rb').read())
    old = struct.unpack_from('<I', x, 0x3C)[0]
    assert old == 0x16e978, hex(old)
    if not os.environ.get('FR_ARM_NOBSS'): struct.pack_into('<I', x, 0x3C, BSS_ORG - 0x6B0000 + BSS_LEN)
    open(xout, 'wb').write(x)
    print(f'exheader bss {old:#x} -> {BSS_ORG - 0x6B0000 + BSS_LEN:#x}')

if __name__ == '__main__':
    main(*sys.argv[1:5])
